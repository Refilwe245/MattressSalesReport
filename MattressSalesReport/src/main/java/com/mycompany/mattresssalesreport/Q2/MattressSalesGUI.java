    private void btnProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcessActionPerformed
        // TODO add your handling code here:

    try {
        String customerName = txtCustomerName.getText().trim();

        String selectedProduct =
                jComboBox1.getSelectedItem().toString();

        double productPrice =
                Double.parseDouble(txtEnterPrice.getText().trim());

        if (customerName.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Please enter the customer name.");
            return;
        }

        Data data = new Data();

        String information = data.SaveData(
                customerName, selectedProduct, productPrice);

        javax.swing.JOptionPane.showMessageDialog(this, information);

    } catch (NumberFormatException ex) {

        javax.swing.JOptionPane.showMessageDialog(this,
                "Please enter a valid product price.");

    } catch (java.io.IOException ex) {

        javax.swing.JOptionPane.showMessageDialog(this,
                "Error saving information to data.txt");
       
    }//GEN-LAST:event_btnProcessActionPerformed
    }
